//! TypeScript declarations for the crate's JSON (feature `typescript`), generated
//! with `ts-rs` from the same types serde serializes, so they cannot drift.
//! `examples/export_types.rs` writes them to `rust/bindings/featherweight.d.ts`.
use ts_rs::{Config, TS};

use crate::core::character_cue::CharacterCue;
use crate::core::screenplay_document::{
    ActionAlignment, DialogueContent, DialogueSequence, ScreenplayDocument, ScreenplayElement, StyledText, TextRun,
    TextStyle, TitlePageField,
};
use crate::extraction::PdfInspection;
use crate::import::{Import, ImportWarning, Phase, Progress};

/// The JSON shape of [`Character`](crate::Character): `{ type: "character", text }`.
#[derive(TS)]
#[ts(rename = "Character")]
#[allow(dead_code)]
pub(crate) struct CharacterJson {
    #[ts(rename = "type", inline)]
    kind: CharacterTag,
    text: StyledText,
}

#[derive(TS)]
#[allow(dead_code)]
enum CharacterTag {
    #[ts(rename = "character")]
    Character,
}

/// The JSON shape of [`ImportError`](crate::ImportError), whose `Serialize` is
/// hand-written: `{ code, message }`.
#[derive(TS)]
#[ts(rename = "ImportError")]
#[allow(dead_code)]
struct ImportErrorJson {
    code: ImportErrorCode,
    message: String,
}

/// [`ImportError::code`](crate::ImportError::code) values.
#[derive(TS)]
#[ts(rename_all = "SCREAMING_SNAKE_CASE")]
#[allow(dead_code)]
enum ImportErrorCode {
    NotAPdf,
    Encrypted,
    Corrupt,
    NoEmbeddedText,
    Cancelled,
    Internal,
}

/// Every declaration, as one `.d.ts` module.
pub fn declarations() -> String {
    let cfg = Config::new();
    let declarations = [
        ScreenplayDocument::decl(&cfg),
        TitlePageField::decl(&cfg),
        StyledText::decl(&cfg),
        TextRun::decl(&cfg),
        TextStyle::decl(&cfg),
        ActionAlignment::decl(&cfg),
        ScreenplayElement::decl(&cfg),
        CharacterJson::decl(&cfg),
        DialogueContent::decl(&cfg),
        DialogueSequence::decl(&cfg),
        CharacterCue::decl(&cfg),
        Import::decl(&cfg),
        PdfInspection::decl(&cfg),
        ImportWarning::decl(&cfg),
        ImportErrorJson::decl(&cfg),
        ImportErrorCode::decl(&cfg),
        Progress::decl(&cfg),
        Phase::decl(&cfg),
    ];
    let mut output = String::from(
        "// Generated by `cargo run -p featherweight --example export_types --features typescript`.\n\
         // Do not edit; regenerate after changing the Rust types.\n",
    );
    for declaration in declarations {
        output.push_str("\nexport ");
        output.push_str(&declaration);
        output.push('\n');
    }
    output
}

#[cfg(test)]
mod tests {
    #[test]
    fn committed_declarations_are_current() {
        let committed = include_str!("../../../bindings/featherweight.d.ts").replace("\r\n", "\n");
        assert_eq!(
            committed,
            super::declarations(),
            "rust/bindings/featherweight.d.ts is stale; run the export_types example"
        );
    }
}
